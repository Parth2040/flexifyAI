// Syncs ref_img/ -> public/references/ and generates lib/references.ts.
// Workflow: drop images into ref_img/, then run `node scripts/gen-references.mjs`
// (also runs automatically on `prebuild`).
import {
  readdirSync,
  writeFileSync,
  copyFileSync,
  rmSync,
  existsSync,
  mkdirSync,
} from "node:fs";
import { join, extname } from "node:path";

const exts = [".jpg", ".jpeg", ".png", ".webp", ".jfif"];
const isImage = (f) => exts.includes(extname(f).toLowerCase());

const srcDir = join(process.cwd(), "ref_img");
const destDir = join(process.cwd(), "public", "references");
mkdirSync(destDir, { recursive: true });

// 1. If a source ref_img/ folder exists, mirror its images into public/references/
//    with clean sequential names (ref-1.ext, ref-2.ext, ...).
if (existsSync(srcDir)) {
  for (const f of readdirSync(destDir)) {
    if (isImage(f)) rmSync(join(destDir, f));
  }
  const srcFiles = readdirSync(srcDir)
    .filter(isImage)
    .sort((a, b) =>
      a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" })
    );
  srcFiles.forEach((f, i) => {
    copyFileSync(join(srcDir, f), join(destDir, `ref-${i + 1}${extname(f).toLowerCase()}`));
  });
}

// 2. List the served images.
let files = [];
try {
  files = readdirSync(destDir)
    .filter(isImage)
    .sort((a, b) =>
      a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" })
    );
} catch {
  files = [];
}

// 3. Deterministic shuffle so similar/duplicate photos aren't side by side,
//    but the order stays stable across builds (seeded).
function seededShuffle(arr, seed) {
  let s = seed >>> 0;
  const rand = () => {
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

const list = seededShuffle(files.map((f) => `/references/${f}`), 20260629);
const out = `// AUTO-GENERATED by scripts/gen-references.mjs — do not edit by hand.
export const REFERENCE_IMAGES: string[] = ${JSON.stringify(list, null, 2)};
`;

writeFileSync(join(process.cwd(), "lib", "references.ts"), out);
console.log(`Wrote lib/references.ts with ${list.length} reference image(s).`);
